"""Configure or inspect a Vidyalayaa DevKit over its USB serial port."""

import argparse
import getpass
import http.client
import json
import re
import ssl
import sys
import time
from pathlib import Path
from urllib.parse import urlsplit

import serial


def command(port, message, prefix, timeout=12):
    port.reset_input_buffer()
    port.write(message + b"\n")
    port.flush()
    until = time.monotonic() + timeout
    while time.monotonic() < until:
        reply = port.readline().decode("utf-8", errors="replace").strip()
        if reply.startswith(prefix):
            return reply
    raise RuntimeError("The firmware did not respond. Check the COM port and close other serial apps.")


def verify_reader(origin, code, secret, root_ca):
    endpoint = urlsplit(origin)
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    context.load_verify_locations(cadata=root_ca)
    connection = http.client.HTTPSConnection(endpoint.hostname, endpoint.port, context=context, timeout=12)
    try:
        connection.request(
            "GET",
            "/api/v1/device/config",
            headers={"Authorization": "Bearer " + secret, "X-Device-Id": code},
        )
        status = connection.getresponse().status
        if status != 200:
            raise RuntimeError(f"Device config returned HTTP {status}. Check the school claim and reader credential.")
    finally:
        connection.close()


def provision(port, args, status):
    if "mode=enrollment" not in status:
        raise RuntimeError("Boot the board with GPIO32 connected to GND, then run this command again.")
    origin = args.api.rstrip("/")
    endpoint = urlsplit(origin)
    if not re.fullmatch(r"https://[a-zA-Z0-9.-]+(?::[0-9]+)?", origin) or not endpoint.hostname:
        raise RuntimeError("--api must be an HTTPS origin without a path.")
    root_ca = Path(args.ca_file).read_text(encoding="ascii").strip() + "\n"
    code = args.device or input("Device code: ").strip()
    if not re.fullmatch(r"[A-Z0-9_-]{3,64}", code):
        raise RuntimeError("Enter the device code shown by Vidyalayaa.")
    ssid = input("Wi-Fi name (SSID): ")
    password = getpass.getpass("Wi-Fi password: ")
    secret = getpass.getpass("Vidyalayaa device secret: ")
    if not 1 <= len(ssid.encode()) <= 32 or not (
        8 <= len(password.encode()) <= 63 or re.fullmatch(r"[0-9a-fA-F]{64}", password)
    ):
        raise RuntimeError("Enter a valid Wi-Fi name and WPA2 password.")
    if not re.fullmatch(r"[A-Za-z0-9_-]{32,256}", secret):
        raise RuntimeError("Enter the device secret generated by Vidyalayaa.")
    if len(root_ca) > 4096 or not root_ca.startswith("-----BEGIN CERTIFICATE-----"):
        raise RuntimeError("Provide the API's trusted root CA certificate in PEM format.")
    verify_reader(origin, code, secret, root_ca)
    payload = {"code": code, "ssid": ssid, "password": password, "origin": origin,
               "secret": secret, "root_ca": root_ca}
    request = b"PROVISION " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode()
    if len(request) >= 6144:
        raise RuntimeError("The configuration exceeds the device input limit.")
    result = command(port, request, "VIDYALAYAA PROVISION ")
    if result != "VIDYALAYAA PROVISION OK RESTART_REQUIRED":
        raise RuntimeError("The reader rejected the configuration. Verify the device code and storage state.")
    print("Configuration saved. Remove the GPIO32 jumper if fitted, then reset to start gate mode.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", required=True, help="Serial port, for example COM9")
    parser.add_argument("--status", action="store_true", help="Read firmware and component status only")
    parser.add_argument("--api", help="HTTPS API origin")
    parser.add_argument("--ca-file", help="Trusted API root CA PEM file")
    parser.add_argument("--device", help="Device code from Vidyalayaa")
    args = parser.parse_args()
    if not args.status and not (args.api and args.ca_file):
        parser.error("provide --api and --ca-file when provisioning")
    try:
        with serial.Serial(args.port, 115200, timeout=0.5, write_timeout=3) as port:
            time.sleep(2)
            status = command(port, b"STATUS", "VIDYALAYAA STATUS ")
            print(status)
            if not args.status:
                provision(port, args, status)
    except (OSError, ValueError, RuntimeError, http.client.HTTPException) as error:
        print(f"Setup check failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
