import { createHash } from 'node:crypto';
import type { SupabaseClient } from '@supabase/supabase-js';
import type { PGlite } from '@electric-sql/pglite';

// Disposable tests mirror the provider-owned tables; application migrations must
// never create or replace these tables in a real Supabase project.
export const providerSessionSchema = `
CREATE TABLE IF NOT EXISTS auth.sessions(id uuid PRIMARY KEY,user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now(),
not_after timestamptz,refreshed_at timestamp,user_agent text,ip inet);
CREATE TABLE IF NOT EXISTS auth.refresh_tokens(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
token text,session_id uuid REFERENCES auth.sessions(id) ON DELETE CASCADE,revoked boolean DEFAULT false);
REVOKE ALL ON auth.sessions,auth.refresh_tokens FROM PUBLIC,anon,authenticated;`;

export function fixtureBearer(original: string) {
  let claims: Record<string, unknown> = {};
  try {
    claims = JSON.parse(Buffer.from(original.split('.')[1], 'base64url').toString());
  } catch {}
  const h = createHash('sha256').update(original).digest('hex');
  return (
    'fixture.' +
    Buffer.from(
      JSON.stringify({
        ...claims,
        fixture_original: original,
        session_id:
          claims.session_id ||
          `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`,
        exp: claims.exp || Math.floor(Date.now() / 1000) + 3600,
      }),
    ).toString('base64url') +
    '.fixture'
  );
}

// Keep existing role/auth simulations while giving them real provider sessions.
// A session is seeded once; revocation cannot recreate it on later requests.
export function withProviderSessions(db: Pick<PGlite, 'query'>, client: SupabaseClient) {
  const getUser = client.auth.getUser.bind(client.auth),
    seeded = new Set<string>();
  client.auth.getUser = (async (token?: string) => {
    if (!token) return getUser(token);
    let claims: Record<string, unknown>;
    try {
      claims = JSON.parse(Buffer.from(token.split('.')[1], 'base64url').toString());
    } catch {
      return { data: { user: null }, error: { status: 401, message: 'Invalid fixture token' } };
    }
    const result = await getUser(
      typeof claims.fixture_original === 'string' ? claims.fixture_original : token,
    );
    if (
      result.data.user &&
      typeof claims.session_id === 'string' &&
      !seeded.has(claims.session_id)
    ) {
      seeded.add(claims.session_id);
      await db.query(
        "INSERT INTO auth.sessions(id,user_id,user_agent,ip) VALUES($1,$2,'Mozilla/5.0 (Windows NT 10.0) Chrome/130.0','192.0.2.10') ON CONFLICT DO NOTHING",
        [claims.session_id, result.data.user.id],
      );
    }
    return result;
  }) as typeof client.auth.getUser;
  return client;
}
